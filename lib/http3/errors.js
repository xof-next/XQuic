'use strict';

const H3 = Object.freeze({
  NO_ERROR: 0x100,
  GENERAL_PROTOCOL_ERROR: 0x101,
  INTERNAL_ERROR: 0x102,
  STREAM_CREATION_ERROR: 0x103,
  CLOSED_CRITICAL_STREAM: 0x104,
  FRAME_UNEXPECTED: 0x105,
  FRAME_ERROR: 0x106,
  EXCESSIVE_LOAD: 0x107,
  ID_ERROR: 0x108,
  SETTINGS_ERROR: 0x109,
  MISSING_SETTINGS: 0x10a,
  REQUEST_REJECTED: 0x10b,
  REQUEST_CANCELLED: 0x10c,
  REQUEST_INCOMPLETE: 0x10d,
  MESSAGE_ERROR: 0x10e,
  CONNECT_ERROR: 0x10f,
  VERSION_FALLBACK: 0x110,
  QPACK_DECOMPRESSION_FAILED: 0x200,
  QPACK_ENCODER_STREAM_ERROR: 0x201,
  QPACK_DECODER_STREAM_ERROR: 0x202,
  DATAGRAM_ERROR: 0x33
});

const H3_NAMES = Object.freeze(Object.fromEntries(Object.entries(H3).map(([k,v])=>[v,k])));

function h3Name(code){ 
  return H3_NAMES[Number(code)] || 'H3_UNKNOWN';
}

module.exports = { H3, H3_NAMES, h3Name};